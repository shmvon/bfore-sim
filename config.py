"""Settings of the simulation, read from environment variables.

Where the data lives (see _resolve_data_dir):
  - running locally: the folder 'data' next to this file (never in git or the image);
  - in the container: /app/data, the folder where the CaaS volume is mounted.
  Nothing has to be seeded: the game data is generated by the code, and fdb.db,
  prefs.db and the session key are created on first use, so an empty volume is fine.
  To restart from a download, put fdb.db (and optionally prefs.db) in seeds/: they
  are copied into an empty data folder at startup, never over existing files.

On the server (CaaS), set these as environment variables of the container:
  DATA_DIR       optional: another folder for the data (default: see above).
  PORT           port the app listens on when started with 'python app.py';
                 default 8500 (the Docker image sets 5000).
  DOWNLOAD_CODE  code to download the collected data on /download.
                 Without it, downloading is switched off.

When running locally, the same settings can be put in a file '.env' next to this
file (one NAME=value per line, see .env.example). That file is never committed
to git or copied into the Docker image. Real environment variables take priority.
"""
import os

_ENV_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '.env')


def _load_env_file(path):
    if not os.path.exists(path):
        return
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#') or '=' not in line:
                continue
            name, value = line.split('=', 1)
            os.environ.setdefault(name.strip(), value.strip().strip('"').strip("'"))


_load_env_file(_ENV_FILE)

# Version of the app, shown on the landing page. Raise it for each new release.
VERSION = '6.0'

_HERE = os.path.dirname(os.path.abspath(__file__))
CONTAINER_DATA_DIR = '/app/data'


def _in_container():
    """True inside the Docker image (the Dockerfile sets BFORE_CONTAINER=1)."""
    return os.environ.get('BFORE_CONTAINER') == '1' or os.path.exists('/.dockerenv')


def _resolve_data_dir():
    """DATA_DIR if set; else /app/data in the container; else <project>/data locally."""
    if os.environ.get('DATA_DIR'):
        return os.path.abspath(os.environ['DATA_DIR'])
    if _in_container():
        return CONTAINER_DATA_DIR
    return os.path.join(_HERE, 'data')


DATA_DIR = _resolve_data_dir()
FDB_PATH = os.path.join(DATA_DIR, 'fdb.db')        # collected results of all players
PREFS_PATH = os.path.join(DATA_DIR, 'prefs.db')    # last used country/language per visitor
DOWNLOAD_CODE = os.environ.get('DOWNLOAD_CODE', '').strip()
PORT = int(os.environ.get('PORT', '8500'))
SECRET_KEY_PATH = os.path.join(DATA_DIR, '.secret_key')


def secret_key():
    """Session key: SECRET_KEY if set, else one kept in DATA_DIR/.secret_key.

    Keeping it in the data folder (the volume on the server) means players keep
    their game when the container restarts.
    """
    if os.environ.get('SECRET_KEY'):
        return os.environ['SECRET_KEY']
    os.makedirs(DATA_DIR, exist_ok=True)
    try:
        with open(SECRET_KEY_PATH, encoding='ascii') as f:
            key = f.read().strip()
        if key:
            return key
    except FileNotFoundError:
        pass
    import secrets
    key = secrets.token_hex(32)
    with open(SECRET_KEY_PATH, 'w', encoding='ascii') as f:
        f.write(key)
    os.chmod(SECRET_KEY_PATH, 0o600)
    return key


SEEDS_DIR = os.path.join(_HERE, 'seeds')
SEED_FILES = ('fdb.db', 'prefs.db')


def seed_data_dir():
    """Copy seeds/<file> into DATA_DIR when that file is missing there. Never overwrites."""
    import shutil
    os.makedirs(DATA_DIR, exist_ok=True)
    for name in SEED_FILES:
        src, dst = os.path.join(SEEDS_DIR, name), os.path.join(DATA_DIR, name)
        if os.path.exists(src) and not os.path.exists(dst):
            shutil.copy2(src, dst)
            print(f"Seeded {dst} from {src}")


def report():
    """Print the settings in use (never the code itself), so the server log shows them."""
    os.makedirs(DATA_DIR, exist_ok=True)
    path = os.path.abspath(DATA_DIR)
    writable = os.access(path, os.W_OK)
    where = 'container' if _in_container() else 'local'
    print(f"DATA_DIR = {path} ({where}; writable: {writable}; "
          f"fdb.db {'found' if os.path.exists(FDB_PATH) else 'not there yet, starts empty'})")
    print(f"DOWNLOAD_CODE is {'set' if DOWNLOAD_CODE else 'NOT set: downloading is switched off'}")
